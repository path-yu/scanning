package blob

import (
	"strings"
	"testing"
)

func TestLooksBinary(t *testing.T) {
	cases := []struct {
		name string
		data []byte
		want bool
	}{
		{name: "empty", data: nil, want: false},
		{name: "json", data: []byte(`{"code":200,"message":"ok"}`), want: false},
		{name: "utf8-chinese", data: []byte("网易云音乐播放列表"), want: false},
		{name: "truncated-utf8-tail", data: []byte(strings.Repeat("a", 200) + "\xe4\xb8"), want: false},
		{name: "eapi-like", data: []byte{'s', 0xcc, 0x0f, 0x94, 0x16, 0x00, 0xff, 0x7f}, want: true},
		{name: "netease-eapi-sample", data: []byte{
			0x73, 0xcc, 0x0f, 0x94, 0x16, 0x2c, 0x59, 0x6b, 0x2b, 0x12, 0xd8, 0x62, 0xca, 0x7a, 0x4e, 0x91,
			0xd1, 0xdb, 0x59, 0x6e, 0xf4, 0x17, 0x70, 0x5d, 0x3d, 0x4a, 0x96, 0xc8, 0x57, 0x82, 0x24, 0x63,
			0x80, 0xa2, 0x7b, 0xf1, 0x5a, 0x89, 0x97, 0x72, 0x4f, 0x2f, 0x7f, 0x0c, 0xca, 0x96, 0xc0, 0x27,
			0x4a, 0x60, 0xce, 0x8a, 0x8a, 0x20, 0x1d, 0x72, 0x63, 0xef, 0x58, 0x31, 0x59, 0x0f, 0x13, 0x73,
		}, want: true},
		{name: "invalid-utf8", data: []byte{0xff, 0xfe, 0xfd, 0xfc, 0xfb, 0xfa}, want: true},
		{name: "control-heavy", data: []byte{0x01, 0x02, 0x03, 0x04, 0x05, 0x06}, want: true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := LooksBinary(tc.data); got != tc.want {
				t.Fatalf("LooksBinary(%v) = %v, want %v", tc.data, got, tc.want)
			}
		})
	}
}
